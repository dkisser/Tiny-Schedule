/**
 * 界面上暂时收起来的功能入口。
 *
 * # 为什么是「藏入口」而不是「关功能」
 *
 * 定时任务要的是从面板上暂时收起来，功能本身一点没动。所以这份开关只管侧栏那一行
 * 导航项的显隐：数据模型、调度器、列表页、详情面板、IPC 契约、运行历史——全部留在
 * 原处，一条也没删。「入口」和「能力」是两件事，这里关掉的只是前者。
 *
 * # 藏起来之后，什么还在跑
 *
 * - **已存在的定时任务照常触发。** 调度器在 `bridge/bootstrap.ts` 里无条件起跑
 *   （`startScheduler(store)`），与界面上的入口没有任何关系：到点照常执行、照常落
 *   运行记录、照常发系统通知。入口藏起来不会让任何一条已配置的规则停摆。
 * - **人没法再新建或改它们。** 列表页与详情面板的唯一入口就是侧栏这一行，入口藏
 *   起来之后它们不可达——这是「隐藏」的应有之义，不是缺陷。
 *
 * # 怎么恢复
 *
 * 把 `SHOW_SCHEDULED_TASKS_ENTRY` 改回 `true` 即可。没有数据迁移，没有清理动作：
 * `data.json` 里的定时任务一直原样留着，恢复的那一刻它们就重新出现在侧栏里，
 * 期间照常到点触发。
 */
export const SHOW_SCHEDULED_TASKS_ENTRY: boolean = false;
